def data_to_ano(df):
    import pandas as pd

    df = df.copy()

    # Converte Data
    df['Data'] = pd.to_datetime(
        df['Data'],
        format='%m/%Y'
    )

    # Cria o ano
    df['Ano'] = df['Data'].dt.year

    # Mantém somente dezembro
    df = df[df['Data'].dt.month == 12].copy()

    # Remove Data
    df = df.drop(columns='Data')

    return df


def codigo_to_ri(df):
    df = df.copy()

    df["Codigo"] = (
        df["Codigo"]
        .astype("string")
        .str.replace(r"\.0$", "", regex=True)
        .str.zfill(6)
    )
    df["RI"] = df["Codigo"].map(regioes)
    return df